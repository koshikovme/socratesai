import { test, expect } from '@playwright/test'
import { installNativeFixture } from './nativeFixture'

async function login(page, role) {
  await page.goto('/login')
  await page.getByLabel('Email', { exact: true }).fill(`${role}@example.test`)
  await page.getByLabel('Password', { exact: true }).fill('fixture-password')
  await page.getByRole('button', { name: 'Login', exact: true }).click()
  await expect(page).toHaveURL(/\/dashboard$/)
}
async function writeCode(page, code) {
  // Monaco's accessible input sits behind its rendered lines; focus through the visible surface.
  await page.locator('.monaco-editor .view-lines').click({ position: { x: 30, y: 10 } })
  await page.keyboard.press('ControlOrMeta+A')
  await page.keyboard.insertText(code)
}

test('teacher publishes verified multilingual problem/collection; student edits, receives WS feedback, runs and submits', async ({ page }) => {
  const state = await installNativeFixture(page)
  const browserErrors = []
  page.on('pageerror', e => browserErrors.push(e.message))
  await login(page, 'teacher')
  await page.getByRole('link', { name: 'Teaching', exact: true }).click()
  await page.getByRole('link', { name: 'New problem', exact: true }).click()
  await page.getByLabel('Title', { exact: true }).fill('Sum two integers')
  await page.getByLabel('Topic', { exact: true }).fill('Basics')
  await page.getByLabel('Statement', { exact: true }).fill('Read two integers and print their sum. <img src=x onerror=alert(1)>')
  for (const key of ['python3', 'java', 'cpp17']) {
    await page.getByLabel('Add language', { exact: true }).selectOption(key)
    await page.getByRole('button', { name: 'Add language', exact: true }).click()
  }
  await page.getByLabel('Starter code', { exact: true }).nth(0).fill('print(0)')
  await page.getByLabel('Starter code', { exact: true }).nth(1).fill('class Main {}')
  await page.getByLabel('Starter code', { exact: true }).nth(2).fill('int main() {}')
  for (let i = 0; i < 2; i++) {
    await page.getByRole('button', { name: 'Add test', exact: true }).click()
    await page.getByLabel('Input', { exact: true }).nth(i).fill(i ? '100 200' : '2 3')
    await page.getByLabel('Expected output', { exact: true }).nth(i).fill(i ? '300' : '5')
  }
  await page.getByLabel('Hidden test', { exact: true }).nth(1).check()
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page).toHaveURL(/\/teacher\/problems\/11$/)
  await expect(page.getByRole('button', { name: 'Publish verified version' })).toBeDisabled()
  for (const key of ['python3', 'java', 'cpp17']) await page.getByLabel(`Reference source · ${key}`, { exact: true }).fill(`reference ${key}`)
  await page.getByRole('button', { name: 'Verify reference solution', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Publish verified version' })).toBeEnabled()
  await page.getByRole('button', { name: 'Publish verified version' }).click()
  await expect(page.getByText('Verified version published.', { exact: true })).toBeVisible()
  expect(state.reference.solutions).toHaveLength(3)
  await page.getByRole('link', { name: 'Teaching', exact: true }).click()
  await page.getByRole('link', { name: 'New collection', exact: true }).click()
  await page.getByLabel('Title', { exact: true }).fill('Introductory practice')
  await page.getByLabel('Description', { exact: true }).fill('Native problems, pinned versions.')
  await page.getByRole('button', { name: 'Add problem', exact: true }).click()
  await page.getByRole('button', { name: 'Save collection and order', exact: true }).click()
  await expect(page).toHaveURL(/\/teacher\/collections\/31$/)
  await page.getByRole('button', { name: 'Publish collection', exact: true }).click()
  await expect(page.getByText('Collection published.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Logout', exact: true }).click()
  await login(page, 'student')
  await page.getByRole('button', { name: 'Collections', exact: true }).click()
  await page.getByRole('link', { name: 'Open collection', exact: true }).click()
  await expect(page.getByTestId('collection-progress')).toHaveText('0 of 1 solved')
  await page.getByRole('link', { name: 'Open problem', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Sum two integers', exact: true })).toBeVisible()
  await expect(page.locator('.statement-card img')).toHaveCount(0)
  await writeCode(page, 'print(sum(map(int, input().split())))')
  await expect.poll(() => state.snapshots.at(-1)?.code).toBe('print(sum(map(int, input().split())))')
  const initialId = state.snapshots.at(-1).editorSessionId
  const initialRevision = state.snapshots.at(-1).codeRevision
  await expect(page.getByText('Review your input parsing (WS).', { exact: true })).toBeVisible()
  await expect(page.locator('.policy-mode')).toHaveText('ML')
  await page.getByLabel('Language', { exact: true }).selectOption('java')
  await writeCode(page, 'class Main { public static void main(String[] args) {} }')
  await expect.poll(() => state.snapshots.at(-1)?.languageKey).toBe('java')
  await expect(page.locator('.policy-mode')).toContainText('RULE')
  await page.getByLabel('Language', { exact: true }).selectOption('cpp17')
  await writeCode(page, 'int main() { return 0; }')
  await expect.poll(() => state.snapshots.at(-1)?.code).toBe('int main() { return 0; }')
  await page.getByLabel('Language', { exact: true }).selectOption('python3')
  await expect.poll(() => state.snapshots.at(-1)?.code).toBe('print(sum(map(int, input().split())))')
  expect(state.snapshots.at(-1).editorSessionId).toBe(initialId)
  expect(state.snapshots.at(-1).codeRevision).toBeGreaterThan(initialRevision)
  expect(state.snapshots.every(item => !('studentId' in item) && !('attemptNo' in item))).toBe(true)
  await page.getByRole('button', { name: 'Run samples', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Execution result' })).toContainText('ACCEPTED')
  expect(state.accepted).toBe(false)
  await page.getByRole('button', { name: 'Submit', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Execution result' })).toContainText('Server attempt 1')
  await expect(page.getByRole('region', { name: 'Execution result' })).toContainText('ACCEPTED')
  await expect(page.getByRole('region', { name: 'Execution result' })).toContainText('Hidden test 2: ACCEPTED')
  await expect(page.locator('body')).not.toContainText('HIDDEN_ECHO_MUST_NOT_RENDER')
  await expect(page.locator('body')).not.toContainText('HIDDEN_DIAGNOSTICS')
  expect(state.posts).toHaveLength(2)
  expect(state.posts[0].body).not.toHaveProperty('collectionId')
  expect(state.posts[1].body.collectionId).toBe(31)
  expect(state.posts[1].body.idempotencyKey).toMatch(/^[0-9a-f-]{36}$/)
  page.on('dialog', dialog => dialog.accept())
  await page.getByRole('link', { name: 'Back to collection', exact: true }).click()
  await expect(page.getByTestId('collection-progress')).toHaveText('1 of 1 solved')
  await page.getByRole('link', { name: 'Catalog', exact: true }).click()
  await expect(page.getByTestId('solved')).toContainText('SOLVED')
  await page.goto('/teacher/problems/11')
  await expect(page).toHaveURL(/\/dashboard$/)
  await page.getByRole('button', { name: 'Logout', exact: true }).click()
  expect(await page.evaluate(() => localStorage.getItem('token'))).toBeNull()
  expect(await page.evaluate(() => sessionStorage.length)).toBe(0)
  expect(browserErrors).toEqual([])
})

